#!/usr/bin/env python3
"""Bootstrap a new EzyPlatform / EzyArticle project folder and validate its connection.

Usage:
    ezy new [target] [--admin-url URL] [--site NAME]
                               [--copy-skills] [--update-skills] [--no-example]
    ezy token [admin_url]
    ezy check [target]

`create` mirrors the VS Code extension's "EzyArticle: Create Project"
(environment.json template, AGENTS.md, AGENTS_UPDATED.md, README.md,
api/v1/media/, pages/example-page/, .gitignore) and adds an ezy section at the top
of AGENTS.md. With --copy-skills the ezy-* skills are also vendored into
.claude/skills (for agents without plugin support or to pin a version). Existing files are never overwritten, except
AGENTS_UPDATED.md, which the extension also rewrites on every update.
The admin token is never asked for, read aloud or printed: the human pastes it
into environment.json.
"""
import argparse
import glob
import json
import os
import re
import shlex
import shutil
import stat
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SKILL_DIR = os.path.dirname(HERE)
SKILLS_ROOT = os.path.dirname(SKILL_DIR)
TEMPLATES = os.path.join(SKILL_DIR, 'templates')
sys.path.insert(0, os.path.join(SKILLS_ROOT, 'ezy-shared'))
from ezy_output import print_status  # noqa: E402

TOKEN_PLACEHOLDER = '<Your admin access token>'
URL_PLACEHOLDER_RE = re.compile(r'^<.*>$')
EZY_SECTION_MARK = '# Working With This Project'
REPO = 'cppai-vn/agents-plugins'
GITIGNORE_LINES = ['environment.json', '.artifacts/', '*.pyc']
EXAMPLE_META = {'slug': 'example-page', 'title': 'Example Page', 'summary': '', 'featuredImageName': '',
                'pageType': 'PAGE', 'contentType': 'HTML', 'status': 'DRAFT', 'metadata': {}}
HTML_TEMPLATE = '<!-- Auto-generated by the EzyArticle VS Code tools. -->\n'


def extension_templates():
    """Starter texts from the newest installed EzyArticle extension, else the bundled copies."""
    bundled = {name: open(os.path.join(TEMPLATES, name), encoding='utf-8').read()
               for name in ('AGENTS.md', 'AGENTS_UPDATED.md', 'README.md')}
    candidates = []
    for base in ('~/.vscode/extensions', '~/.vscode-insiders/extensions', '~/.cursor/extensions'):
        candidates += glob.glob(os.path.expanduser(f'{base}/youngmonkeys.ezyarticle-*/out/constants.js'))

    def version(path):
        m = re.search(r'ezyarticle-(\d+)\.(\d+)\.(\d+)', path)
        return tuple(int(x) for x in m.groups()) if m else (0, 0, 0)

    if not candidates or not shutil.which('node'):
        return bundled, 'bundled templates (extension 0.2.8)'
    newest = max(candidates, key=version)
    script = ("const c=require(process.argv[1]);process.stdout.write(JSON.stringify("
              "{a:c.AGENTS_CONTENT,u:c.AGENTS_UPDATED_CONTENT,r:c.README_CONTENT}))")
    try:
        out = json.loads(subprocess.run(['node', '-e', script, newest], capture_output=True, text=True,
                                        timeout=20, check=True).stdout)
        if all(out.get(k) for k in 'aur'):
            label = 'extension ' + '.'.join(map(str, version(newest)))
            return {'AGENTS.md': out['a'], 'AGENTS_UPDATED.md': out['u'], 'README.md': out['r']}, label
    except (subprocess.SubprocessError, ValueError):
        pass
    return bundled, 'bundled templates (extension 0.2.8)'


def write_if_missing(path, text, report, root):
    rel = os.path.relpath(path, root)
    if os.path.exists(path):
        report.append(f'  = {rel} (exists, kept)')
        return False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(text)
    report.append(f'  + {rel}')
    return True


def ensure_gitignore(root, report):
    path = os.path.join(root, '.gitignore')
    current = open(path, encoding='utf-8').read() if os.path.exists(path) else ''
    lines = {line.strip() for line in current.splitlines()}
    missing = [line for line in GITIGNORE_LINES if line not in lines]
    if missing:
        sep = '' if not current or current.endswith('\n') else '\n'
        with open(path, 'w', encoding='utf-8') as fh:
            fh.write(current + sep + '\n'.join(missing) + '\n')
        report.append(f"  ~ .gitignore (+ {', '.join(missing)})")
    else:
        report.append('  = .gitignore (already ignores secrets and artifacts)')


def copy_skills(root, update, report):
    dest_root = os.path.join(root, '.claude', 'skills')
    if os.path.realpath(dest_root) == os.path.realpath(SKILLS_ROOT):
        report.append('  = .claude/skills (this is the skill source project)')
        return
    ignore = shutil.ignore_patterns('*.pyc', '__pycache__')
    for name in sorted(os.listdir(SKILLS_ROOT)):
        src = os.path.join(SKILLS_ROOT, name)
        if not (name.startswith('ezy-') and os.path.isdir(src)):
            continue
        dest = os.path.join(dest_root, name)
        if os.path.exists(dest) and not update:
            report.append(f'  = .claude/skills/{name} (exists, kept; --update-skills to refresh)')
            continue
        if os.path.exists(dest):
            shutil.rmtree(dest)
        shutil.copytree(src, dest, ignore=ignore)
        report.append(f"  {'~' if update else '+'} .claude/skills/{name}")


def cmd_create(args):
    root = os.path.abspath(args.target)
    os.makedirs(root, exist_ok=True)
    templates, source = extension_templates()
    report = []

    env_template = [
        {'name': 'production', 'default': True,
         'admin_url': args.admin_url or '<EzyPlatform Production Admin URL for This Environment>',
         'admin_access_token': TOKEN_PLACEHOLDER},
        {'name': 'beta', 'admin_url': '<EzyPlatform Beta Admin URL for This Environment>',
         'admin_access_token': TOKEN_PLACEHOLDER,
         'notes': 'This environment is optional and can be removed if not available.'},
    ]
    env_path = os.path.join(root, 'environment.json')
    if write_if_missing(env_path, json.dumps(env_template, indent=2) + '\n', report, root):
        os.chmod(env_path, stat.S_IRUSR | stat.S_IWUSR)
    ensure_gitignore(root, report)

    site = args.site or (re.sub(r'^https?://', '', args.admin_url).split('/')[0] if args.admin_url else os.path.basename(root))
    ezy_section = (open(os.path.join(TEMPLATES, 'ezy-section.md'), encoding='utf-8').read()
                   .replace('{{SITE}}', site).replace('{{REPO}}', REPO))
    agents_path = os.path.join(root, 'AGENTS.md')
    if not write_if_missing(agents_path, ezy_section + templates['AGENTS.md'], report, root):
        if EZY_SECTION_MARK not in open(agents_path, encoding='utf-8').read():
            report.append('    ! AGENTS.md has no ezy section; prepend templates/ezy-section.md after the human agrees')
    with open(os.path.join(root, 'AGENTS_UPDATED.md'), 'w', encoding='utf-8') as fh:
        fh.write(templates['AGENTS_UPDATED.md'])
    report.append('  ~ AGENTS_UPDATED.md (always refreshed, like the extension)')
    write_if_missing(os.path.join(root, 'README.md'), templates['README.md'], report, root)

    media = os.path.join(root, 'api', 'v1', 'media')
    report.append('  = api/v1/media/' if os.path.isdir(media) else '  + api/v1/media/')
    os.makedirs(media, exist_ok=True)
    if not args.no_example:
        page = os.path.join(root, 'pages', 'example-page')
        for name in ('content.html', 'head.html', 'foot.html'):
            write_if_missing(os.path.join(page, name), HTML_TEMPLATE, report, root)
        write_if_missing(os.path.join(page, 'meta.json'), json.dumps(EXAMPLE_META, indent=2) + '\n', report, root)
    if args.copy_skills or args.update_skills:
        copy_skills(root, args.update_skills, report)

    print(f'Initialized {root}\nstarter text: {source}')
    print('\n'.join(report))
    print()
    print_token_help(args.admin_url, root)
    return 0


def print_token_help(admin_url, root=None):
    base = admin_url.rstrip('/') if admin_url and not URL_PLACEHOLDER_RE.match(admin_url) else '<admin_url>'
    env_file = os.path.join(root, 'environment.json') if root else 'environment.json'
    print(f"""Next: connect this project to your EzyPlatform admin
  1. Open {base}/admins/me and sign in as an admin.
  2. Find the "Access Token" field, click to reveal it and confirm with your password.
  3. Copy the token and paste it yourself into {env_file}
     -> the entry with "default": true -> "admin_access_token".
     Also set "admin_url" to {base if base != '<admin_url>' else 'your admin URL, e.g. https://admin.example.com'}.
     Do not send the token in chat; it grants the full rights of that admin account.
     Remove the "beta" entry if you have no beta server.
  4. Validate: ezy check{' ' + shlex.quote(root) if root else ''}
  5. Open this project in your coding agent and use the installed ezy-guide skill for content work.""")


def cmd_check(args):
    root = os.path.abspath(args.target)
    env_path = os.path.join(root, 'environment.json')
    problems = []
    if not os.path.isfile(env_path):
        print_status(f'environment.json missing in {root}; run "ezy new" first', False)
        return 1
    try:
        envs = json.load(open(env_path, encoding='utf-8'))
    except ValueError as err:
        print_status(f'environment.json is not valid JSON: {err}', False)
        return 1
    defaults = [e for e in envs if e.get('default')] if isinstance(envs, list) else []
    if len(defaults) != 1:
        problems.append(f'exactly one environment must have "default": true (found {len(defaults)})')
    env = defaults[0] if defaults else {}
    url = (env.get('admin_url') or '').strip()
    token = (env.get('admin_access_token') or '').strip()
    if not url or URL_PLACEHOLDER_RE.match(url) or not url.startswith(('http://', 'https://')):
        problems.append('admin_url is not set to a real http(s) URL')
    if not token or token == TOKEN_PLACEHOLDER or URL_PLACEHOLDER_RE.match(token):
        problems.append('admin_access_token is still the placeholder')
    gitignore = os.path.join(root, '.gitignore')
    if not os.path.isfile(gitignore) or 'environment.json' not in open(gitignore, encoding='utf-8').read().split():
        problems.append('.gitignore does not ignore environment.json (the token would be committed)')
    if os.stat(env_path).st_mode & (stat.S_IRGRP | stat.S_IROTH):
        print_status('environment.json is readable by other users; consider: chmod 600 environment.json')
    if problems:
        print_status('not ready:', False)
        for problem in problems:
            print_status(problem, False)
        print()
        print_token_help(url, root)
        return 1

    import ezy_client  # noqa: E402  (needs a valid environment.json)
    try:
        roles = [r.get('name') for r in ezy_client.request_json('GET', '/api/v1/admins/me/roles', env=env) or []]
        web = ezy_client.request_text('/api/v1/settings/web-url', env).strip()
        fragments = ezy_client.request_json('GET', '/ezyarticle/api/v1/pages/fragments?keyword=', env=env) or {}
    except ezy_client.EzyError as err:
        hint = {401: 'token rejected: copy it again from /admins/me', 403: 'blocked or forbidden: check the URL and that the token belongs to an admin'}
        print_status(f'connection failed: HTTP {err.status} — {hint.get(err.status, err.body[:200])}', False)
        return 1
    except OSError as err:
        print_status(f'cannot reach {url}: {err}', False)
        return 1
    print_status(f"connected to {url} as environment '{env.get('name')}'", True)
    print_status(f"roles: {', '.join(roles) or 'none'}" + ('  (full admin rights — keep this token private)' if 'super_admin' in roles else ''), True)
    print_status(f'public site: {web}', True)
    print_status(f'fragment groups on server: {len(fragments)} ({sum(len(v) for v in fragments.values())} fragments)', True)
    local_pages = sorted(os.listdir(os.path.join(root, 'pages'))) if os.path.isdir(os.path.join(root, 'pages')) else []
    print_status(f"local pages: {', '.join(local_pages) or 'none'}")
    print('\nNext: open this project in your coding agent and use the installed ezy-guide skill. '
          'It routes content work to ezy-sync, ezy-author, ezy-publish and the other installed skills.')
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest='cmd', required=True)
    c = sub.add_parser('create')
    c.add_argument('target', nargs='?', default='.')
    c.add_argument('--admin-url')
    c.add_argument('--site')
    c.add_argument('--copy-skills', action='store_true')
    c.add_argument('--no-example', action='store_true')
    c.add_argument('--update-skills', action='store_true')
    t = sub.add_parser('token-help')
    t.add_argument('admin_url', nargs='?')
    k = sub.add_parser('check')
    k.add_argument('target', nargs='?', default='.')
    args = parser.parse_args()
    if args.cmd == 'token-help':
        print_token_help(args.admin_url)
        return 0
    return cmd_create(args) if args.cmd == 'create' else cmd_check(args)


if __name__ == '__main__':
    sys.exit(main())
